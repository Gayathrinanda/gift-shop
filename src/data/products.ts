/** Build a 4-image gallery from a category pool, varying offset per product so galleries differ. */
function gallery(pool: string[], seed: number): string[] {
  const rnd = seedRandom(seed)
  const start = Math.floor(rnd() * pool.length)
  const imgs = [0, 1, 2, 3].map((i) => pool[(start + i) % pool.length])
  return imgs.map((id) => unsplash(id, 900))
}

